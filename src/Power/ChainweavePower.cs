namespace ChaosHeidemarie.Power;

[RegisterPower]
public class ChainweavePower : ModPowerTemplate
{
    public override PowerType Type => PowerType.Buff;
    public override PowerStackType StackType => PowerStackType.Counter;
    public override PowerAssetProfile AssetProfile => new(
        IconPath: "res://ArtWorks/images/power/ChainweavePower_Small.png",
        BigIconPath: "res://ArtWorks/images/power/ChainweavePower_Big.png"
    );

    public override decimal ModifyDamageAdditive(Creature? target, decimal amount, ValueProp props, Creature? dealer, CardModel? cardSource,
        CardPlay? cardPlay)
    {
        if (!props.IsPoweredAttack()) return 0m;
        if (dealer != Owner) return 0m;
        if (cardSource == null) return 0m;
        var powerAmount = Owner.GetPowerAmount<InherentMemoryPower>();
        return powerAmount * Amount;
    }

    public override async Task AfterSideTurnEnd(PlayerChoiceContext choiceContext, CombatSide side, IEnumerable<Creature> participants)
    {
        if (side == CombatSide.Player)
        {
            await PowerCmd.Remove(this);
        }
    }
}